import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { expect, test } from '@playwright/test';

test.use({ reducedMotion: 'reduce' });

test('runs a persisted simulated scan, exports its receipt, retries and restores after refresh', async ({ page }) => {
  const config = readFileSync(fileURLToPath(new URL('../../../.env', import.meta.url)), 'utf8');
  const token = /^AEGISFORGE_API_TOKEN=(.+)$/m.exec(config)?.[1].trim();
  if (!token) throw new Error('Initialize local .env before browser tests.');
  await page.goto('/');
  await page.getByLabel('访问令牌').fill(token);
  await page.getByRole('button', { name: '连接服务' }).click();
  await expect(page.getByText('已连接本地服务')).toBeVisible();
  const ingest = page.locator('.ingest-panel');
  await ingest.getByRole('button', { name: '载入开发示例' }).click();
  await ingest.getByRole('button', { name: '保存并预览特征' }).click();
  await expect(ingest.locator('.artifact-preview')).toContainText('CWE-78');
  const panel = page.locator('.scan-panel');
  const model = panel.getByRole('combobox', { name: '模型', exact: true });
  await model.click();
  await page.locator('.ant-select-dropdown:not(.ant-select-dropdown-hidden)').getByText('模拟模型', { exact: true }).click();
  await expect(panel.getByText('模拟模型不执行真实分析，任务会明确标为部分完成。')).toBeVisible();
  await panel.getByRole('button', { name: '创建检测任务' }).click();
  const detail = panel.getByRole('article', { name: '任务详情' });
  await expect(detail.locator('h3').getByText('部分完成', { exact: true })).toBeVisible();
  await expect(detail).toContainText('模拟（未分析）');
  await expect(detail).toContainText('CWE-78');
  await expect(detail).toContainText('外部调用 0 次');
  await detail.getByText('检测凭证 · 输入与分析方案').click();
  const downloadEvent = page.waitForEvent('download');
  await detail.getByRole('button', { name: '下载检测凭证' }).click();
  const download = await downloadEvent;
  const receipt = JSON.parse(readFileSync((await download.path())!, 'utf8'));
  expect(receipt.receipt.schema_version).toBe('receipt-1.0');
  expect(receipt.analysis_complete).toBe(false);
  const exported = JSON.stringify(receipt);
  expect(exported).not.toContain(token);
  expect(exported).not.toContain('os.system');
  expect(exported).not.toContain('display_name');
  await detail.getByRole('button', { name: '按当前配置重试' }).click();
  await expect(detail).toContainText('此前尝试（1）');
  await expect(detail.locator('h3').getByText('部分完成', { exact: true })).toBeVisible();
  const restoredUrl = page.url();
  expect(restoredUrl).toMatch(/scan=[0-9a-f-]{36}/);
  await page.reload();
  await expect(panel.getByText('重新连接服务后可恢复此检测任务。')).toBeVisible();
  await page.getByLabel('访问令牌').fill(token);
  await page.getByRole('button', { name: '连接服务' }).click();
  await expect(detail).toContainText('此前尝试（1）');
  await expect(detail.locator('h3').getByText('部分完成', { exact: true })).toBeVisible();
  await expect(detail).toContainText('外部调用 0 次');
  await expect(detail).toContainText('模拟（未分析）');
  await detail.getByText('检测凭证 · 输入与分析方案').click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/m3-scan-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/m3-scan-mobile.png', fullPage: true });
});
